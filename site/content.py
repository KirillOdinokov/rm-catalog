def _decaps(s):
    """«ГИДРОИЗОЛЯЦИОННАЯ СМЕСЬ ДЛЯ БЕТОНА» -> «гидроизоляционная смесь для бетона»."""
    s = (s or "").strip()
    if not s:
        return ""
    if s != s.upper():
        return s
    out = []
    for w in s.split(" "):
        core = w.strip(".,;:()«»\"")
        if core.upper() in ABBR:
            out.append(w)
        else:
            out.append(w.lower())
    res = " ".join(out)
    return res[:1].upper() + res[1:] if res else res


def _sent(s):
    s = (s or "").strip()
    if not s:
        return ""
    if not s.endswith((".", "!", "?", ";")):
        s += "."
    return s[:1].upper() + s[1:]


def _cut(s, limit):
    s = (s or "").strip()
    if len(s) <= limit:
        return s
    cut = s[:limit].rsplit(" ", 1)[0].rstrip(" ,;:—-")
    return cut + "…"


def _sec_name(x):
    """«АДГЕЗИОННЫЕ СОСТАВЫ И КЛЕИ» -> «Адгезионные составы и клеи»."""
    if not x or x != x.upper():
        return x
    x = x.lower()
    for k in ("жд", "жб", "пу", "мсц", "тпмк", "hdpe", "tpe", "pu", "нп", "эпо"):
        x = re.sub(r"\b%s\b" % k, k.upper(), x)
    return x[:1].upper() + x[1:]


def _differs(a, b):
    """Строки не дублируют друг друга."""
    a, b = (a or "").strip().lower(), (b or "").strip().lower()
    if not a or not b:
        return True
    return not (a in b or b in a)


def _strip_name_intro(intro, name):
    """Убирает из начала описания повтор названия и связки «это / представляет собой»."""
    m = re.match(r"^(.{3,140}?)\s[-—–]\s(.+)$", intro)
    if m:
        left, right = m.group(1), m.group(2)
        a = set(re.findall(r"[а-яёa-z0-9]+", left.lower()))
        b = set(re.findall(r"[а-яёa-z0-9]+", name.lower()))
        if a and b and len(a & b) / max(1, len(a)) > 0.45:
            intro = right
    intro = re.sub(r"^(это|представляет собой|конструктивно|собой)\s+", "", intro, flags=re.I)
    return intro.strip(" ,.;—-")


def _strip_caps_names(s, name):
    """Убирает из техтекста остатки заводских заголовков капсом (имя товара)."""
    nt = set(re.findall(r"[А-ЯЁA-Z0-9]+", name.upper()))

    def repl(m):
        toks = set(re.findall(r"[А-ЯЁA-Z0-9]+", m.group(0)))
        return "" if toks and toks <= nt else m.group(0)
    s = re.sub(r"\b[А-ЯЁA-Z0-9®/.\-]{8,}(?:\s+[А-ЯЁA-Z0-9®/.\-]{2,}){0,3}\b", repl, s)
